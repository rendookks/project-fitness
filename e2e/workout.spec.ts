import { expect, test } from '@playwright/test';
import { onboard } from './helpers';

test('inline logging, validation, warmups, reload, finish and previous-value autofill', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await onboard(page);
  await page.goto('/train');
  await page.getByRole('textbox', { name: 'Workout name', exact: true }).fill('Upper strength');
  await page.getByTestId('start-workout').click();
  await page.getByRole('button', { name: 'Add exercise', exact: true }).click();
  await page.getByRole('textbox', { name: 'Search exercises' }).fill('bench');
  await page.getByRole('button', { name: 'Add Barbell Bench Press', exact: true }).click();
  await page.getByRole('button', { name: 'Add set · Barbell Bench Press', exact: true }).click();
  const weight=page.getByRole('textbox', { name: 'Weight (kg) set 1 of Barbell Bench Press', exact: true });
  await weight.fill('60');
  await page.getByRole('textbox', { name: 'Repetitions set 1 of Barbell Bench Press', exact: true }).fill('0');
  await page.getByRole('checkbox', { name: 'Complete set 1 of Barbell Bench Press', exact: true }).click();
  await expect(page.getByText('Enter 1–999 repetitions.')).toBeVisible();
  await page.getByRole('textbox', { name: 'Repetitions set 1 of Barbell Bench Press', exact: true }).fill('5');
  await page.getByRole('checkbox', { name: 'Complete set 1 of Barbell Bench Press', exact: true }).click();
  await expect(page.getByRole('checkbox', { name: 'Complete set 1 of Barbell Bench Press' })).toBeChecked();
  await page.getByRole('button', { name: 'Add set · Barbell Bench Press', exact: true }).click();
  await page.getByRole('button', { name: 'Set 2 details of Barbell Bench Press', exact: true }).click();
  await page.getByRole('textbox', { name: 'Weight (kg)', exact: true }).fill('20');
  await page.getByRole('button', { name: 'Warm-up', exact: true }).click();
  await page.getByRole('button', { name: 'Not completed yet', exact: true }).click();
  await page.getByRole('button', { name: 'Save set', exact: true }).click();
  await page.reload();
  await expect(weight).toHaveValue('60');
  await expect(page.getByRole('heading', { name: 'Upper strength', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Finish workout', exact: true }).click();
  await page.getByRole('button', { name: 'Save workout', exact: true }).click();
  await expect(page.getByText('SAVED SESSION', { exact: true })).toBeVisible();
  await expect(page.getByText('300 kg', { exact: true })).toBeVisible();
  await page.goto('/train');
  await page.getByTestId('start-workout').click();
  await page.getByRole('button', { name: 'Add exercise', exact: true }).click();
  await page.getByRole('button', { name: 'Add Barbell Bench Press', exact: true }).click();
  await page.getByRole('button', { name: 'Add set · Barbell Bench Press', exact: true }).click();
  await expect(weight).toHaveValue('60');
  await expect(page.getByRole('checkbox', { name: 'Complete set 1 of Barbell Bench Press' })).not.toBeChecked();
  await page.getByRole('button', { name: 'Discard workout', exact: true }).click();
  await page.getByRole('button', { name: 'Delete', exact: true }).click();
  await expect(page.getByTestId('start-workout')).toBeVisible();
  expect(errors).toEqual([]);
});
